// End-to-end check of "describe an agent": fill, save, view, compare, share link round trip.
import { createRequire } from 'module'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const B = 'http://localhost:5450/'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1512, height: 945 }, deviceScaleFactor: 2 })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto(B + '?a=radar&s=car')
await page.click('text=+ Describe an agent')
await page.fill('.d-name', 'Store support bot (example)')
await page.fill('input[placeholder="What it does, in one line"]', 'Answers order and refund questions on a store website.')
await page.click('.q:has(#f-route) .choice >> text=Decides its own')
await page.fill('#f-map', 'Order history\nRefund tool, up to $50')
await page.fill('#f-destination', 'Resolve refund requests without a person')
await page.click('.q:has(#f-instructor) .choice >> text=Approves risky actions')
await page.fill('#f-instructor', 'Refunds over $50 go to a person')
await page.fill('#f-run', 'Reads the customer message\nLooks up the order\n! Order number not found\nAsks the customer to confirm the email\nIssues a $32 refund')
await page.waitForTimeout(300)
await page.screenshot({ path: 'shots/d-1-describe.png' })
const sideKnown = await page.textContent('.big-known')
await page.click('text=Save and view')
await page.waitForSelector('.kpis')
await page.waitForTimeout(400)
await page.screenshot({ path: 'shots/d-2-agent.png' })
const kpiKnown = await page.textContent('.kpi:nth-child(2) .kpi-value')
const asks = await page.$$eval('.ask-chip', e => e.map(x => x.textContent))
await page.click('.stop >> text=On the road')
await page.waitForTimeout(300)
await page.screenshot({ path: 'shots/d-3-road.png' })
await page.click('text=Compare all')
await page.waitForTimeout(400)
await page.screenshot({ path: 'shots/d-4-compare.png', fullPage: true })
// share link round trip in a fresh browser with empty storage
await page.click('text=Store support bot (example)')
await page.click('text=Edit')
await page.click('text=Copy share link').catch(() => {})
const link = await page.evaluate(() => import('/src/lib/described.tsx').then(m => m.toLink(m.loadAll()[0])))
const fresh = await (await browser.newContext({ viewport: { width: 1512, height: 945 } })).newPage()
await fresh.goto(link)
await fresh.waitForSelector('.kpis')
const sharedName = await fresh.textContent('.page-head h1')
console.log(JSON.stringify({ sideKnown, kpiKnown, asks, sharedName, linkLength: link.length, errors }, null, 1))
await browser.close()
